function LearningLessonFlow({ lesson, onExit, onComplete }) {
  const hasTips = Array.isArray(lesson.tips) && lesson.tips.length > 0;
  const [stage, setStage] = useState(hasTips ? "tips" : "quiz"); // tips | quiz | result
  const [score, setScore] = useState(0);
  return (
    <div className="pv-modal-backdrop" onClick={stage==="result" ? undefined : onExit}>
      <div className="pv-modal" onClick={e=>e.stopPropagation()} style={{ maxHeight:"88vh", overflowY:"auto" }}>
        <div style={{ display:"flex", justifyContent:"space-between", alignItems:"center", marginBottom:16 }}>
          <h3 style={{ margin:0, fontSize:15.5, fontWeight:800, overflow:"hidden", textOverflow:"ellipsis", whiteSpace:"nowrap" }}>{lesson.title}</h3>
          {stage!=="result" && <button onClick={onExit} className="pv-btn" style={{ background:"var(--surface)", width:32, height:32, borderRadius:11, display:"grid", placeItems:"center", flexShrink:0 }}><X size={15}/></button>}
        </div>
        {stage==="tips" && <LearningTips lesson={lesson} onDone={()=>setStage("quiz")}/>}
        {stage==="quiz" && <LearningQuiz lesson={lesson} isTest={!hasTips} onFinish={(s)=>{ setScore(s); setStage("result"); onComplete(s, lesson.quiz.length); }}/>}
        {stage==="result" && <LearningResult lesson={lesson} score={score} onClose={onExit}/>}
      </div>
    </div>
  );
}

