function LearningQuiz({ lesson, onFinish, isTest }) {
  const [qIdx, setQIdx] = useState(0);
  const [picked, setPicked] = useState(null);
  const [score, setScore] = useState(0);
  const q = lesson.quiz[qIdx];
  const isLast = qIdx === lesson.quiz.length - 1;
  const answered = picked !== null;

  const choose = (i) => {
    if (answered) return;
    haptic(i===q.correct ? [15,25,15] : 12);
    if (i===q.correct) playSuccessSound(); else playErrorSound();
    setPicked(i);
    if (i===q.correct) setScore(s=>s+1);
  };

  const next = () => {
    if (isLast) { onFinish(score + (picked===q.correct && !answered ? 1 : 0)); return; }
    setQIdx(i=>i+1); setPicked(null);
  };

  return (
    <div className="pv-fade">
      <div className="pv-progress-bg" style={{ height:8, marginBottom:18 }}>
        <div className="pv-progress-fill" style={{ width:`${((qIdx+(answered?1:0))/lesson.quiz.length)*100}%`, background:"linear-gradient(90deg,#3ECF8E,#5CC9FF)" }}/>
      </div>
      <p style={{ fontSize:11.5, fontWeight:700, color:"var(--text-dim)", margin:"0 0 6px", display:"flex", alignItems:"center", gap:6 }}>
        <HelpCircle size={13}/> سوال {toPersianDigits(qIdx+1)} از {toPersianDigits(lesson.quiz.length)}
      </p>
      <div className="pv-card pv-soft-pop" key={qIdx} style={{
        padding:20, marginBottom:16,
        ...(isTest ? {
          background:"rgba(255,166,84,0.14)",
          border:"1.5px solid rgba(255,166,84,0.55)",
        } : {})
      }}>
        <p style={{ margin:0, fontSize:15.5, fontWeight:800, lineHeight:1.8 }}>{q.q}</p>
      </div>

      <div style={{ display:"flex", flexDirection:"column", gap:10, marginBottom:18 }}>
        {q.options.map((opt,i) => {
          let bg = "var(--surface)", color = "var(--text)", border = "1.5px solid var(--border)", Icon = null;
          if (answered) {
            if (i===q.correct) { bg = "rgba(52,211,153,0.16)"; color="var(--success)"; border="1.5px solid var(--success)"; Icon = ThumbsUp; }
            else if (i===picked) { bg = "rgba(255,107,107,0.14)"; color="var(--danger)"; border="1.5px solid var(--danger)"; Icon = XCircle; }
          }
          return (
            <button key={i} onClick={()=>choose(i)} className="pv-btn" style={{
              padding:"14px 16px", borderRadius:18, textAlign:"right", fontSize:13.5, fontWeight:700,
              background:bg, color, border, display:"flex", alignItems:"center", justifyContent:"space-between", gap:10
            }}>
              <span>{opt}</span>
              {Icon && <Icon size={17}/>}
            </button>
          );
        })}
      </div>

      {answered && (
        <button onClick={()=>{ haptic(8); playTickSound(); next(); }} className="pv-btn pv-btn-primary pv-soft-pop" style={{ width:"100%", padding:"14px 0", borderRadius:16, fontSize:14 }}>
          {isLast ? "پایان آزمون" : "سوال بعدی"}
        </button>
      )}
    </div>
  );
}

