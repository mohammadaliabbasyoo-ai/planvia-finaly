function computeAchievementProgress(stats){
  const base = ACHIEVEMENTS.filter(a=>!a.meta).map(a => {
    const val = a.get(stats) || 0;
    const pct = Math.min(100, Math.round((val/a.goal)*100));
    return { ...a, value:val, pct, unlocked: val >= a.goal };
  });
  const unlockedCount = base.filter(a=>a.unlocked).length;
  const meta = ACHIEVEMENTS.filter(a=>a.meta).map(a => {
    const val = unlockedCount;
    const pct = Math.min(100, Math.round((val/a.goal)*100));
    return { ...a, value:val, pct, unlocked: val >= a.goal };
  });
  return [...base, ...meta];
}

